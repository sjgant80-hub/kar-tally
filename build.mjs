// build.mjs — one source of truth for the page, the gated kernel and the Agensi skill script.
//
// The verifier's logic lives in index.html (the live page), between the KERNEL:BEGIN and KERNEL:END
// markers. This script copies that block byte-for-byte into:
//   kernel.mjs          — the module the tests and the witness mutation gate run against
//   scripts/<name>.mjs  — the single-file skill script (the block + cli.mjs), which is what Agensi ships
// so the page a person uses, the kernel the gate proves and the script an agent runs are the same code.
//
//   node build.mjs           regenerate both files
//   node build.mjs --check   exit 1 if either file differs from what index.html + cli.mjs produce (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';

const NAME = JSON.parse(readFileSync('package.json', 'utf8')).name;

export function extractKernel(html) {
  const b = html.match(/^.*KERNEL:BEGIN.*$/m);
  const e = html.match(/^.*KERNEL:END.*$/m);
  if (!b || !e || e.index < b.index) throw new Error('index.html: KERNEL:BEGIN / KERNEL:END markers missing or out of order');
  return html.slice(b.index + b[0].length + 1, e.index);
}

// Every top-level declaration in the block is exported, so nothing in the page is untestable.
// `var a = 1, b = [2, 3], c = f(4, 5);` declares a, b and c: split at commas outside brackets and strings.
function declaredNames(rest) {
  const names = [];
  let depth = 0, quote = null, part = '';
  for (const ch of rest + ',') {
    if (quote) { if (ch === quote) quote = null; part += ch; continue; }
    if (ch === '"' || ch === "'" || ch === '`') quote = ch;
    else if ('([{'.includes(ch)) depth++;
    else if (')]}'.includes(ch)) depth--;
    else if (ch === ';' && depth === 0) break;
    if (ch === ',' && depth === 0) {
      const m = part.match(/^\s*([A-Za-z_$][\w$]*)/);
      if (m) names.push(m[1]);
      part = '';
    } else part += ch;
  }
  const m = part.match(/^\s*([A-Za-z_$][\w$]*)/);
  if (m) names.push(m[1]);
  return names;
}

export function topLevelNames(code) {
  const names = [];
  for (const m of code.matchAll(/^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:var|let|const)\s+(.*)$/gm)) {
    if (m[1]) names.push(m[1]);
    else names.push(...declaredNames(m[2]));
  }
  return [...new Set(names)];
}

export function kernelModule(block) {
  return '// GENERATED by build.mjs from the KERNEL block in index.html: edit index.html, then run `node build.mjs`.\n' +
    block + 'export { ' + topLevelNames(block).join(', ') + ' };\n';
}

// The skill script must run on its own: Agensi writes it unchanged to a temporary file and runs it,
// and a script there cannot read any other file of the package. So the kernel block is inlined and
// the CLI's import of ./kernel.mjs is dropped (its names are already declared by the block).
export function skillScript(block, cli) {
  const body = cli.split('\n').filter((l) => !/^import .* from '\.\/kernel\.mjs';\s*$/.test(l)).join('\n');
  return '#!/usr/bin/env node\n' +
    `// ${NAME} — Agensi skill script, generated by build.mjs in the sjgant80-hub/${NAME} repository.\n` +
    '// The KERNEL block below is byte-identical to the logic of the live page (index.html) and to\n' +
    '// kernel.mjs, which the tests and the witness mutation gate run against. No network, no dependencies,\n' +
    '// writes no files: it reads the input you name and prints a JSON report to stdout.\n' +
    '// MIT licence.\n' +
    '// ---- KERNEL (from index.html) ----\n' + block +
    '// ---- CLI (from cli.mjs) ----\n' + body;
}

function main() {
  const block = extractKernel(readFileSync('index.html', 'utf8'));
  const cli = readFileSync('cli.mjs', 'utf8');
  const outputs = [['kernel.mjs', kernelModule(block)], [`scripts/${NAME}.mjs`, skillScript(block, cli)]];
  if (process.argv.includes('--check')) {
    let drift = 0;
    for (const [path, want] of outputs) {
      const have = existsSync(path) ? readFileSync(path, 'utf8') : null;
      if (have !== want) { console.error(`✗ ${path} is out of date: run node build.mjs`); drift++; }
      else console.log(`✓ ${path} matches index.html${path.startsWith('scripts/') ? ' + cli.mjs' : ''}`);
    }
    process.exit(drift ? 1 : 0);
  }
  mkdirSync('scripts', { recursive: true });
  for (const [path, text] of outputs) { writeFileSync(path, text); console.log(`wrote ${path} (${Buffer.byteLength(text)} bytes)`); }
}

main();
